//! Set documents: the declared facts of every instrument set, written from
//! the descriptors that own them.
//!
//! Each set crate has one document under `docs/instruments/`. The
//! hand-written half states the set's intended function, its failure
//! presentation, and the requirements it answers to; the generated half
//! is a block between two markers that lists what each descriptor
//! declares — render space, layers/bands, groups, spatial bounds, underlay
//! contract, accepted intents, auxiliary channels, config keys, regions,
//! extreme states, and raster baselines.

use std::path::{Path, PathBuf};

use indicate_instrument_registry::{DesignFrame, PanelDescriptor, PanelSet, RenderSpace};
use indicate_instrument_scene::{
    LayerId,
    angular::AngularLayerId,
    volume::{Extent3D, VolumeBandId},
};
use indicate_instrument_state::GroupId;

use crate::error::XtaskError;
use crate::output::print_line;
use crate::workspace::repo_root;

const BEGIN_MARKER: &str =
    "<!-- descriptor facts: begin (generated by `cargo xtask gen-set-docs`; do not edit) -->";
const END_MARKER: &str = "<!-- descriptor facts: end -->";

/// One documented set crate: its document, its package, and the sets it exports.
struct Documented {
    document: &'static str,
    package: &'static str,
    sets: &'static [&'static PanelSet],
}

/// Every set crate in the workspace.
const DOCUMENTED: &[Documented] = &[
    Documented {
        document: "set-panels.md",
        package: "indicate-instrument-panels",
        sets: &[
            &indicate_instrument_panels::BUILTIN_SET,
            &indicate_instrument_panels::CONFIG_SET,
        ],
    },
    Documented {
        document: "set-template.md",
        package: "indicate-instrument-template",
        sets: &[&indicate_instrument_template::TEMPLATE_SET],
    },
    Documented {
        document: "set-hmd.md",
        package: "indicate-instrument-hmd",
        sets: &[&indicate_instrument_hmd::HMD_SET],
    },
    Documented {
        document: "set-hud.md",
        package: "indicate-instrument-hud",
        sets: &[
            &indicate_instrument_hud::HUD_SCREEN_SET,
            &indicate_instrument_hud::HUD_COMBINER_SET,
        ],
    },
    Documented {
        document: "set-volumes.md",
        package: "indicate-instrument-volumes",
        sets: &[&indicate_instrument_volumes::VOLUMES_SET],
    },
];

/// Parses `gen-set-docs [--check]`.
pub fn parse_args(args: &[String]) -> Result<bool, XtaskError> {
    match args {
        [] => Ok(false),
        [flag] if flag == "--check" => Ok(true),
        other => Err(XtaskError::Usage {
            message: format!("gen-set-docs takes only --check, got {other:?}"),
        }),
    }
}

/// Regenerates the descriptor block of every set document, or with
/// `check` only compares and refuses on a difference.
pub fn run(check: bool) -> Result<(), XtaskError> {
    let dir = documents_dir();
    let mut stale = Vec::new();
    for documented in DOCUMENTED {
        let path = dir.join(documented.document);
        let current = read(&path)?;
        let generated = render_block(documented);
        let updated = splice(&current, &generated, &path)?;
        if updated == current {
            print_line(&format!("current: {}", path.display()));
            continue;
        }
        if check {
            stale.push(path.display().to_string());
            continue;
        }
        std::fs::write(&path, &updated).map_err(|source| XtaskError::File {
            action: "writing",
            path: path.display().to_string(),
            source,
        })?;
        print_line(&format!("wrote {}", path.display()));
    }
    if stale.is_empty() {
        return Ok(());
    }
    Err(XtaskError::SetDocStale {
        documents: stale.join(", "),
    })
}

fn documents_dir() -> PathBuf {
    std::env::var_os("INDICATE_SET_DOCS_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| repo_root().join("docs/instruments"))
}

fn read(path: &Path) -> Result<String, XtaskError> {
    std::fs::read_to_string(path).map_err(|source| XtaskError::File {
        action: "reading",
        path: path.display().to_string(),
        source,
    })
}

/// Replaces the text between the markers with `generated`, keeping
/// everything outside them byte for byte.
fn splice(current: &str, generated: &str, path: &Path) -> Result<String, XtaskError> {
    let (Some(begin), Some(end)) = (current.find(BEGIN_MARKER), current.find(END_MARKER)) else {
        return Err(XtaskError::SetDocMarkers {
            path: path.display().to_string(),
        });
    };
    if end < begin {
        return Err(XtaskError::SetDocMarkers {
            path: path.display().to_string(),
        });
    }
    let mut out = String::with_capacity(current.len() + generated.len());
    out.push_str(&current[..begin]);
    out.push_str(BEGIN_MARKER);
    out.push('\n');
    out.push_str(generated);
    out.push_str(END_MARKER);
    out.push_str(&current[end + END_MARKER.len()..]);
    Ok(out)
}

fn render_block(documented: &Documented) -> String {
    let mut out = String::new();
    out.push_str(&format!("\nCrate: `{}`\n", documented.package));
    for set in documented.sets {
        out.push_str(&format!("\n### Set `{}`\n", set.id));
        for panel in set.panels {
            render_panel(&mut out, panel);
        }
    }
    out.push('\n');
    out
}

fn render_panel(out: &mut String, panel: &PanelDescriptor) {
    out.push_str(&format!(
        "\n#### Panel `{}` — {}\n\n",
        panel.id, panel.title
    ));
    out.push_str("| Declared | Value |\n|---|---|\n");
    row(out, "Render space", panel.space.kind_name());
    row(out, "Required layers", &layers(panel));
    row(out, "Required groups", &groups(panel));
    row(out, "Spatial bounds", &spatial_bounds(panel));
    row(out, "Canonical sizes", &canonical_sizes(panel));
    row(out, "Underlay", panel.underlay.name());
    row(out, "Accepted intents", &accepted_intents(panel));
    row(out, "Aux channels", &aux_channels(panel));
    row(out, "Config keys", &config_keys(panel));
    row(out, "Group regions", &regions(panel));
    row(out, "Extreme states", &extreme_states(panel));
    row(out, "Raster baselines", &baselines(panel));
}

fn row(out: &mut String, name: &str, value: &str) {
    out.push_str(&format!("| {name} | {value} |\n"));
}

fn layers(panel: &PanelDescriptor) -> String {
    let mask = panel.required_layers;
    let names: Vec<String> = match panel.space {
        RenderSpace::Planar2D { .. } => (0u8..8)
            .filter(|bit| mask & (1u16 << bit) != 0)
            .map(|bit| match LayerId::from_u8(bit) {
                Some(layer) => format!("{layer:?}"),
                None => format!("unknown layer {bit}"),
            })
            .collect(),
        RenderSpace::AngularSphere { .. } => {
            let mut items: Vec<String> = (0u8..8)
                .filter(|bit| mask & (1u16 << bit) != 0)
                .map(|bit| match AngularLayerId::from_u8(bit) {
                    Some(layer) => format!("{layer:?}"),
                    None => format!("unknown angular {bit}"),
                })
                .collect();
            for bit in 0u8..8 {
                if mask & (1u16 << (8 + bit)) != 0 {
                    match LayerId::from_u8(bit) {
                        Some(layer) => items.push(format!("Overlay({layer:?})")),
                        None => items.push(format!("Overlay({bit})")),
                    }
                }
            }
            items
        }
        RenderSpace::Volume3D { .. } => (0u8..16)
            .filter(|bit| mask & (1u16 << bit) != 0)
            .map(|bit| match VolumeBandId::from_u8(bit) {
                Some(band) => format!("{band:?}"),
                None => format!("unknown band {bit}"),
            })
            .collect(),
    };
    join_or_none(names)
}

fn groups(panel: &PanelDescriptor) -> String {
    let names: Vec<String> = GroupId::ALL
        .iter()
        .filter(|group| panel.required_groups.contains(**group))
        .map(|group| format!("{group:?}"))
        .collect();
    join_or_none(names)
}

fn frame(frame: DesignFrame) -> String {
    format!("{}×{}", frame.width, frame.height)
}

fn extent(ext: Extent3D) -> String {
    format!("{}×{}×{} m", ext.width_m, ext.height_m, ext.depth_m)
}

fn spatial_bounds(panel: &PanelDescriptor) -> String {
    match panel.space {
        RenderSpace::Planar2D {
            frame_min,
            frame_max,
            frame_step,
            aspect_min,
            aspect_max,
            ..
        } => format!(
            "{} to {}, step {}×{}, aspect {} to {}",
            frame(frame_min),
            frame(frame_max),
            frame_step.0,
            frame_step.1,
            aspect_min,
            aspect_max
        ),
        RenderSpace::AngularSphere {
            overlay_frame: Some(ov),
        } => format!("unit sphere + overlay {}", frame(ov)),
        RenderSpace::AngularSphere {
            overlay_frame: None,
        } => "unit sphere".to_string(),
        RenderSpace::Volume3D {
            extent_min_m,
            extent_max_m,
            view_limits,
            ..
        } => format!(
            "{} to {}, zoom {}..={}, pan ±{} m",
            extent(extent_min_m),
            extent(extent_max_m),
            view_limits.zoom_min,
            view_limits.zoom_max,
            view_limits.pan_limit
        ),
    }
}

fn canonical_sizes(panel: &PanelDescriptor) -> String {
    match panel.space {
        RenderSpace::Planar2D {
            canonical_frames, ..
        } => join_or_none(canonical_frames.iter().map(|f| frame(*f)).collect()),
        RenderSpace::AngularSphere {
            overlay_frame: Some(ov),
        } => frame(ov),
        RenderSpace::AngularSphere {
            overlay_frame: None,
        } => "unit sphere".to_string(),
        RenderSpace::Volume3D {
            canonical_extents_m,
            ..
        } => join_or_none(canonical_extents_m.iter().map(|e| extent(*e)).collect()),
    }
}

fn accepted_intents(panel: &PanelDescriptor) -> String {
    join_or_none(
        panel
            .accepted_intents
            .iter()
            .map(|cls| match cls.core_name() {
                Some(name) => format!("`{name}`"),
                None => format!("`0x{:08X}:0x{:04X}`", cls.namespace.0, cls.opcode),
            })
            .collect(),
    )
}

fn aux_channels(panel: &PanelDescriptor) -> String {
    join_or_none(
        panel
            .aux_channels
            .iter()
            .map(|ch| match ch.well_known_name() {
                Some(name) => format!("`{name}`"),
                None => format!("`0x{:08X}`", ch.0),
            })
            .collect(),
    )
}

fn config_keys(panel: &PanelDescriptor) -> String {
    join_or_none(
        panel
            .config_schema
            .iter()
            .map(|key| format!("`0x{:04X}`", key.0))
            .collect(),
    )
}

fn regions(panel: &PanelDescriptor) -> String {
    join_or_none(
        panel
            .group_regions
            .iter()
            .map(|(group, region)| {
                format!(
                    "{group:?} at ({}, {}) size {}×{}",
                    region.x, region.y, region.width, region.height
                )
            })
            .collect(),
    )
}

fn extreme_states(panel: &PanelDescriptor) -> String {
    join_or_none(
        panel
            .extreme_states
            .iter()
            .map(|state| format!("`{}`", state.id))
            .collect(),
    )
}

fn baselines(panel: &PanelDescriptor) -> String {
    join_or_none(
        panel
            .raster_baselines
            .iter()
            .map(|(at, hash)| format!("{} `{hash}`", frame(*at)))
            .collect(),
    )
}

fn join_or_none(items: Vec<String>) -> String {
    if items.is_empty() {
        "none".to_string()
    } else {
        items.join(", ")
    }
}

